"""Regression tests for the four review comments Codex left on PR #497.

Each was reproduced against the code first:
  1. standard Markdown (images/links) in a stranger-written PR title survived `md_cell`;
  2. a PR's history key followed its editable title, so a title edit counted as "resolved + new";
  3. broken wikilinks of an otherwise fresh hub were only in the detail table, never an item;
  4. PR state was read from ONE repo-wide `--limit 200` query, so an old worktree branch could fall out.
"""

from __future__ import annotations

